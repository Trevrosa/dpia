use crate::{SensorDataMutex, data::SensorData, tasks::WifiCredentials};

#[gatt_server]
pub struct Server {
    sensor_data: SensorService,
}

#[gatt_service(uuid = service::ENVIRONMENTAL_SENSING)]
pub struct SensorService {
    #[descriptor(uuid = descriptors::VALID_RANGE, read, value = [0, 100])]
    #[characteristic(uuid = characteristic::HUMIDITY, read)]
    humidity: u8,
    #[characteristic(uuid = characteristic::TEMPERATURE, read)]
    air_temp: f32,
    #[characteristic(uuid = characteristic::HIGH_TEMPERATURE, read)]
    ground_temp: f32,
    #[characteristic(uuid = characteristic::VOC_CONCENTRATION, read)]
    voc: u16,
    #[characteristic(uuid = characteristic::NITROGEN_DIOXIDE_CONCENTRATION, read)]
    nox: u16,
    #[characteristic(uuid = characteristic::PARTICULATE_MATTER_PM10_CONCENTRATION, read)]
    pm10: u16,
    #[characteristic(uuid = characteristic::PARTICULATE_MATTER_PM25_CONCENTRATION, read)]
    pm2_5: u16,
}

pub async fn server_loop<'vals, C: Controller>(
    mut peri: Peripheral<'vals, C, DefaultPacketPool>,
    server: &Server<'vals>,
    global_data: &'static SensorDataMutex,
    wifi: &'static OnceLock<WifiCredentials>,
) -> ! {
    loop {
        let conn = advertise(&mut peri, server).await;
        let conn = match conn {
            Ok(conn) => conn,
            Err(err) => {
                error!("[adv] advertising failed: {}", Debug2Format(&err));
                continue;
            }
        };

        if let Err(err) = handle_connection(server, &conn, global_data).await {
            error!("[gatt] failure while handling connection: {}", err);
        }
    }
}

fn update_server(data: SensorData, server: &Server<'_>) -> Result<(), trouble_host::Error> {
    macro_rules! set_val {
        ($field:ident) => {
            if let Some(val) = data.$field {
                info!("{}: {}", stringify!($field), val);
                server.sensor_data.$field.set(server, &val)?;
            }
        };
    }

    set_val!(humidity);
    set_val!(air_temp);
    set_val!(ground_temp);
    set_val!(voc);
    set_val!(nox);
    set_val!(pm10);
    set_val!(pm2_5);

    Ok(())
}

async fn handle_connection(
    server: &Server<'_>,
    conn: &GattConnection<'_, '_, DefaultPacketPool>,
    global_data: &'static SensorDataMutex,
) -> Result<(), trouble_host::Error> {
    let handle_range = server.sensor_data.handle_range();
    let disconnect_reason = loop {
        match conn.next().await {
            GattConnectionEvent::Disconnected { reason } => break reason,
            GattConnectionEvent::Gatt { event } => {
                let reply = match event {
                    GattEvent::Read(read) => {
                        if handle_range.contains(&read.handle()) {
                            'read_global: {
                                let Ok(global_data) = global_data.try_lock() else {
                                    warn!("[gatt] global_data was locked");
                                    break 'read_global;
                                };
                                if let Err(err) = update_server(*global_data, server) {
                                    warn!("[gatt] failed to update data from global: {}", err);
                                }
                            }
                            info!("[gatt] got read to sensor data");
                            read.accept()
                        } else {
                            warn!("[gatt] got read to invalid handle {:#x}", read.handle());
                            read.reject(AttErrorCode::INVALID_HANDLE)
                        }
                    }
                    GattEvent::Write(write) => {
                        info!(
                            "[gatt] got write with data {} handle {}",
                            write.data(),
                            write.handle()
                        );
                        write.reject(AttErrorCode::WRITE_NOT_PERMITTED)
                    }
                    _ => event.accept(),
                };

                match reply {
                    Ok(reply) => reply.send().await,
                    Err(err) => warn!("[gatt] error sending response: {}", err),
                }
            }
            _ => {}
        }
    };

    info!("[gatt] disconnected: {}", disconnect_reason);

    Ok(())
}

async fn advertise<'vals, 'server, C: Controller>(
    peri: &mut Peripheral<'vals, C, DefaultPacketPool>,
    server: &'server Server<'vals>,
) -> Result<GattConnection<'vals, 'server, DefaultPacketPool>, BleHostError<C::Error>> {
    let mut adv_data = [0; 31];
    let len = AdStructure::encode_slice(
        &[
            // flags must be set first and must include BR_EDR_NOT_SUPPORTED
            AdStructure::Flags(LE_GENERAL_DISCOVERABLE | BR_EDR_NOT_SUPPORTED),
            AdStructure::ServiceUuids16(&[service::ENVIRONMENTAL_SENSING.to_le_bytes()]),
            AdStructure::CompleteLocalName(b"dpia"),
        ],
        &mut adv_data[..],
    )?;
    let advertiser = peri
        .advertise(
            &AdvertisementParameters::default(),
            Advertisement::ConnectableScannableUndirected {
                adv_data: &adv_data[..len],
                scan_data: &[],
            },
        )
        .await?;

    info!("[adv] advertising");
    let conn = advertiser.accept().await?.with_attribute_server(server)?;
    info!("[adv] connection established");

    Ok(conn)
}

pub async fn ble_task<C: Controller, P: PacketPool>(mut runner: Runner<'_, C, P>) {
    loop {
        if let Err(err) = runner.run().await {
            defmt::panic!("ble_task error: {}", defmt::Debug2Format(&err));
        }
    }
}
